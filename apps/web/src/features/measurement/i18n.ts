export const mdict = { ru, kz } as const;

/** t2(key) for the measurement screens; falls back to the key so that an unknown status code stays visible. */
export function useMT() {
  const { lang, pick, t } = useI18n();
  const d: Record<string, string> = mdict[lang];
  const t2 = (key: MKey | string, vars?: Record<string, string | number>) => format(d[key] ?? (mdict.ru as Record<string, string>)[key] ?? key, vars);
  const has = (key: string) => key in d;
  return { t2, lang, pick, t, has };
}
