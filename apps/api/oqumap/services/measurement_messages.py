def _pct(v) -> str:
    try:
        return f"{round(100 * float(v), 1)}%".replace(".0%", "%")
    except (TypeError, ValueError):
        return "—"


def render(code: str, params: dict | None = None, severity: str = "info") -> dict:
    params = dict(params or {})
    p = dict(params)
    for k, v in params.items():
        if isinstance(v, list):
            p[f"{k}_list"] = ", ".join(str(x) for x in v)
        elif isinstance(v, float):
            p[f"{k}_pct"] = _pct(v)
            p[f"{k}_pp"] = f"{round(100 * v, 1)} п.п."
            p[k] = round(v, 3)
    ru, kz = MESSAGES.get(code, (code, code))
    out = {"code": code, "severity": severity, "params": params}
    for lang, tmpl in (("ru", ru), ("kz", kz)):
        try:
            out[f"message_{lang}"] = tmpl.format(**p)
        except (KeyError, IndexError, ValueError):
            out[f"message_{lang}"] = tmpl
    return out


def label(catalog: dict[str, tuple[str, str]], code: str | None) -> dict:
    ru, kz = catalog.get(code or "", (code or "—", code or "—"))
    return {"code": code, "label_ru": ru, "label_kz": kz}
