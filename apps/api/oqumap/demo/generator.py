STRONG = [0.8, 0.7, 0.9, 0.75]
WEAK = [-0.8, -0.7, -0.9, -0.75]


def base_scenario() -> Scenario:
    schools = []
    for i in range(8):
        code = f"S{i + 1:02d}"
        if i < 4:
            classes = [ClassSpec("EDA"), ClassSpec("EDA"), ClassSpec("EDA"), ClassSpec("EDB")]
            eff = STRONG[i]
        else:
            classes = [ClassSpec("EDA"), ClassSpec("EDB"), ClassSpec("EDB"), ClassSpec("EDB")]
            eff = WEAK[i - 4]
        schools.append(SchoolSpec(code, eff, classes))
    return Scenario(
        code="base",
        seed=20260901,
        schools=schools,
        assessments=[
            AssessmentSpec("PRE-2025", "F-PRE", "2025-09-08", 0.03, "pre"),
            AssessmentSpec("POST-2026", "F-POST-1", "2026-05-20", 0.04, "post"),
        ],
        edition_effects={("EDB", "T3"): 0.45},
        repeat_classes={"S02-6Б": 0.3, "S06-6В": 0.3},
    )


def followup_scenario() -> Scenario:
    """Next cohort (2026–2027) in the same schools; known synthetic dynamics: classes on edition A receive
    the decision's action (extra hours + visual-model materials) modelled as +0.40 logits on T3."""
    sc = base_scenario()
    sc.code = "followup"
    sc.seed = 20270210
    sc.academic_year = "2026-2027"
    sc.class_suffix = "-26"
    sc.learner_prefix = "N"
    sc.assessments = [
        AssessmentSpec("PRE-2026", "F-PRE", "2026-09-07", 0.03, "pre"),
        AssessmentSpec("FU-2027", "F-FU", "2027-02-10", 0.04, "post"),
    ]
    sc.edition_effects = {("EDB", "T3"): 0.45, ("EDA", "T3"): 0.40}
    sc.add_across_weight = {"EDA": 2.0, "EDB": 1.5}
    sc.repeat_classes = {}
    return sc


def no_difference_scenario() -> Scenario:
    schools = [SchoolSpec(f"N{i + 1:02d}", eff, [ClassSpec("EDA"), ClassSpec("EDB")])
               for i, eff in enumerate([0.5, -0.4, 0.2, -0.1, 0.4, -0.5, 0.0, 0.3])]
    return Scenario(code="no_difference", seed=20260902, schools=schools,
                    assessments=[AssessmentSpec("PRE-2025", "F-PRE", "2025-09-08", 0.03, "pre"),
                                 AssessmentSpec("POST-2026", "F-POST-1", "2026-05-20", 0.04, "post")],
                    edition_effects={}, add_across_weight={"EDA": 2.0, "EDB": 2.0}, learner_prefix="ND")


