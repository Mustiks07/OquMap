"""Deterministic synthetic data generator (fixed seeds, documented mechanism).

Mechanism (see data/demo/MANIFEST.md, regenerated by the seed):
    ability θ_learner = school_effect + class_effect + N(0, 1)
    pre-test:  P(correct) = σ(1.2·(θ − b_i + 0.3))
    post-test: P(correct) = σ(1.2·(θ + growth + edition_effect[edition, topic] − b_i − topic_shift))
    wrong answers choose a distractor with weights by misconception tag (edition-specific for add_across)
    omissions: P = 0.02 + 0.04·σ(−θ); absences: per assessment rate; optional repeated attempts.
All learners/schools/teachers are fictional pseudonymous codes; editions are "Демонстрационное пособие А/Б".
The size of the corpus does not establish statistical power or a proven effect.
"""

from __future__ import annotations

import csv
import io
import math
from dataclasses import dataclass, field

import numpy as np

from .content import FORMS, ITEMS_BY_CODE

COLUMNS = [
    "school_code", "class_code", "teacher_code", "language", "grade", "academic_year", "edition_code",
    "learner_code", "assessment_code", "form_code", "item_code", "attempt", "status", "score", "response", "date",
]
LETTERS_RU = "АБВГДЕ"


def sigmoid(x: float) -> float:
    return 1.0 / (1.0 + math.exp(-x))


@dataclass
class ClassSpec:
    edition: str
    teacher: str | None = None
    size: int | None = None
    post_form: str | None = None  # overrides scenario post form


@dataclass
class SchoolSpec:
    code: str
    effect: float
    classes: list[ClassSpec]


@dataclass
class AssessmentSpec:
    code: str
    form: str
    date: str
    absent_rate: float = 0.03
    stage: str = "post"


@dataclass
class Scenario:
    code: str
    seed: int
    schools: list[SchoolSpec]
    assessments: list[AssessmentSpec]
    academic_year: str = "2025-2026"
    class_suffix: str = ""
    learner_prefix: str = "L"
    growth: float = 0.6
    topic_shift: dict[str, float] = field(default_factory=lambda: {"T3": 0.35})
    edition_effects: dict[tuple[str, str], float] = field(default_factory=dict)
    add_across_weight: dict[str, float] = field(default_factory=lambda: {"EDA": 3.0, "EDB": 1.5})
    class_sd: float = 0.2
    size_range: tuple[int, int] = (22, 29)
    repeat_classes: dict[str, float] = field(default_factory=dict)  # class code -> share of learners re-taking T3
    repeat_attempts: int = 2
    language: str = "ru"
    grade: int = 6


def generate_rows(sc: Scenario) -> list[dict]:
    rng = np.random.default_rng(sc.seed)
    rows: list[dict] = []
    learner_no = 0
    for school in sc.schools:
        for ci, cls in enumerate(school.classes):
            class_code = f"{school.code}-6{LETTERS_RU[ci]}{sc.class_suffix}"
            teacher = cls.teacher or f"T-{school.code}-{ci + 1}{sc.class_suffix}"
            size = cls.size or int(rng.integers(sc.size_range[0], sc.size_range[1] + 1))
            class_eff = float(rng.normal(0, sc.class_sd))
            for _ in range(size):
                learner_no += 1
                lcode = f"{sc.learner_prefix}{learner_no:04d}"
                theta = school.effect + class_eff + float(rng.normal(0, 1))
                base = dict(
                    school_code=school.code, class_code=class_code, teacher_code=teacher, language=sc.language,
                    grade=sc.grade, academic_year=sc.academic_year, edition_code=cls.edition, learner_code=lcode,
                )
                for a in sc.assessments:
                    form = cls.post_form if (a.stage == "post" and cls.post_form) else a.form
                    common = dict(base, assessment_code=a.code if form == a.form else f"{a.code}-{form}",
                                  form_code=form, date=a.date)
                    if rng.random() < a.absent_rate:
                        rows.append(dict(common, item_code="", attempt=1, status="absent", score="", response=""))
                        continue
                    attempts = 1
                    if a.stage == "post" and class_code in sc.repeat_classes and rng.random() < sc.repeat_classes[class_code]:
                        attempts = sc.repeat_attempts
                    for code in FORMS[form]["items"]:
                        item = ITEMS_BY_CODE[code]
                        n_att = attempts if item.topic == "T3" else 1
                        for att in range(1, n_att + 1):
                            rows.append(dict(common, item_code=code, attempt=att,
                                             **_answer(rng, sc, item, theta + 0.25 * (att - 1), a.stage, cls.edition)))
    return rows


def _answer(rng, sc: Scenario, item, theta: float, stage: str, edition: str) -> dict:
    p_omit = 0.02 + 0.04 * sigmoid(-theta)
    if rng.random() < p_omit:
        return {"status": "omitted", "score": "", "response": ""}
    if stage == "pre":
        logit = 1.2 * (theta - item.difficulty + 0.3)
    else:
        eff = sc.edition_effects.get((edition, item.topic), 0.0)
        logit = 1.2 * (theta + sc.growth + eff - item.difficulty - sc.topic_shift.get(item.topic, 0.0))
    correct = rng.random() < sigmoid(logit)
    if correct:
        return {"status": "answered", "score": "1", "response": item.key}
    letters, weights = [], []
    for letter, (_, tag) in zip(item.letters, item.options, strict=True):
        if letter == item.key:
            continue
        w = 1.0
        if tag == "add_across":
            w = sc.add_across_weight.get(edition, 1.5)
        elif tag in ("numerators_not_scaled", "subtract_across", "mixed_subtract_reverse"):
            w = 1.5
        letters.append(letter)
        weights.append(w)
    pw = np.array(weights) / sum(weights)
    choice = letters[int(rng.choice(len(letters), p=pw))]
    return {"status": "answered", "score": "0", "response": choice}


def to_csv(rows: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=COLUMNS, lineterminator="\n")
    w.writeheader()
    for r in rows:
        w.writerow({k: r.get(k, "") for k in COLUMNS})
    return buf.getvalue()


