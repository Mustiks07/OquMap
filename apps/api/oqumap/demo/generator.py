def errors_sample_rows() -> list[dict]:
    """Small upload with deliberate problems for the import demo (and tests)."""
    sc = Scenario(code="upload_sample", seed=20260907,
                  schools=[SchoolSpec("M01", 0.1, [ClassSpec("EDA", size=12), ClassSpec("EDB", size=12)])],
                  assessments=[AssessmentSpec("PRE-M", "F-PRE", "2025-09-10", 0.0, "pre"),
                               AssessmentSpec("POST-M", "F-POST-1", "2026-05-22", 0.05, "post")],
                  edition_effects={}, learner_prefix="UP")
    rows = generate_rows(sc)
    answered = [r for r in rows if r["status"] == "answered" and r["assessment_code"] == "POST-M"]
    bad = []
    bad.append(dict(answered[0], item_code="I99"))  # unknown item
    bad.append(dict(answered[1], score="3"))  # score above maximum
    bad.append(dict(answered[2], score="abc"))  # not a number
    bad.append(dict(answered[3], learner_code=""))  # missing learner
    bad.append(dict(answered[4], status="maybe"))  # invalid status
    bad.append(dict(answered[5]))  # exact duplicate row
    bad.append(dict(answered[6], item_code="I01"))  # item not on the post form
    bad.append(dict(answered[7], class_code="M01-6Б"))  # learner in two classes
    bad.append(dict(answered[8], learner_code="=HYPERLINK(\"x\")"))  # formula-like code
    bad.append(dict(answered[9], status="omitted", score="1"))  # omitted with score
    return rows + bad


