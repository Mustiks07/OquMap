def unlinked_forms_scenario() -> Scenario:
    sc = no_difference_scenario()
    sc.code = "unlinked_forms"
    sc.seed = 20260904
    sc.learner_prefix = "UF"
    for s in sc.schools:
        s.code = "U" + s.code[1:]
        for c in s.classes:
            if c.edition == "EDB":
                c.post_form = "F-POST-X"
    return sc


