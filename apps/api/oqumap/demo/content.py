def parse_value(text: str) -> F | None:
    """Parse '5/6', '3 1/2', '0,75', '25%', '12' into an exact Fraction. Returns None if not numeric."""
    s = text.strip().replace("−", "-")
    pct = s.endswith("%")
    if pct:
        s = s[:-1].strip()
    s = s.replace(",", ".")
    try:
        if " " in s and "/" in s:
            whole, frac = s.split(" ", 1)
            num, den = frac.split("/")
            w = F(int(whole))
            val = w + (F(int(num), int(den)) if w >= 0 else -F(int(num), int(den)))
        elif "/" in s:
            num, den = s.split("/")
            val = F(int(num), int(den))
        else:
            val = F(s)
    except (ValueError, ZeroDivisionError):
        return None
    return val


def is_reduced(text: str) -> bool:
    s = text.strip()
    if "/" not in s:
        return True
    frac = s.split(" ")[-1]
    num, den = (int(x) for x in frac.split("/"))
    return gcd(num, den) == 1


